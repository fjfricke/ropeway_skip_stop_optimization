"""Validate saved campaign outputs and report them without restarting any solve."""

import argparse
import csv
import hashlib
import json
import pickle
import time
from pathlib import Path

from ropeway_skip_stop_optimization.benchmarking.native_solvers import assess_campaign
from ropeway_skip_stop_optimization.optimization.ddd.cp_sat_certificate import (
    atomic_json,
    read_ddd_cp_sat_checkpoint,
    validate_ddd_cp_sat_domain,
)
from ropeway_skip_stop_optimization.optimization.ddd.native_solvers.optimizer import (
    validate_plan,
)
from ropeway_skip_stop_optimization.optimization.ddd.fixed_timetable_capacity import (
    conservative_count_bound,
)
from ropeway_skip_stop_optimization.optimization.ddd.reservoir_cp_sat_certificate import (
    read_reservoir_cp_checkpoint,
)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    root = args.output.resolve()
    original = json.loads((root / "campaign.json").read_text())
    manifest = json.loads(json.dumps(original))
    rows, curve_rows = [], []
    entries = {e.get("name"): e for e in original["cases"]}
    problems = {}
    for case in ("R", "C"):
        path = root / f"{case}.pickle"
        data = path.read_bytes()
        if (
            hashlib.sha256(data).hexdigest()
            != path.with_suffix(".sha256").read_text().strip()
        ):
            raise ValueError("frozen campaign input changed")
        # Private inputs generated by this campaign, never public checkpoint data.
        problems[case] = pickle.loads(data)[0]
    for repeat in range(3):
        for case in ("R", "C"):
            reference = original["instances"][case]["reference"]
            for backend in original.get(
                "selected_backends", ("cp_sat", "hexaly", "z3")
            ):
                name = f"{case}_{backend}_{repeat}"
                folder = root / name
                entry = entries.get(
                    name,
                    {
                        "name": name,
                        "case": case,
                        "backend": backend,
                        "repetition": repeat,
                    },
                )
                if not (folder / "result.json").exists():
                    entry.setdefault(
                        "status", "INTERRUPTED" if folder.exists() else "NOT_STARTED"
                    )
                    entry.setdefault(
                        "reason",
                        entry.get("metrics", {}).get("supervisor_reason")
                        or (
                            "run ended without result.json"
                            if folder.exists()
                            else "no run started"
                        ),
                    )
                    if not (folder / "best.json").exists():
                        rows.append(entry)
                        continue
                    events_path = folder / "events.jsonl"
                    persisted = []
                    if events_path.exists():
                        for line in events_path.read_text().splitlines():
                            try:
                                persisted.append(json.loads(line))
                            except json.JSONDecodeError:
                                entry["truncated_event_ignored"] = True
                    # Reuse the same conservative integer rounding as the CP
                    # adapters; all campaign objectives use integer native units.
                    bounds = [
                        e["lower_bound"]
                        for e in persisted
                        if backend == "hexaly"
                        and e.get("kind") == "bound"
                        and e.get("lower_bound") is not None
                    ]
                    if backend == "cp_sat":
                        raw_key = "bound_raw" if case == "R" else "raw_lower_bound"
                        bounds = [
                            conservative_count_bound(e[raw_key])
                            for e in persisted
                            if e.get(raw_key) is not None
                        ]
                        bounds = [b for b in bounds if b is not None]
                    built = [e for e in persisted if e.get("kind") == "built"]
                    result = {
                        "status": entry["status"],
                        "lower_bound": max(bounds) if bounds else None,
                        "stats": built[-1].get("stats") if built else None,
                    }
                    entry["recovered_from_live_artifacts"] = True
                    entry["native_solution_events"] = [
                        e for e in persisted if e.get("kind") == "native_solution"
                    ]
                    entry["proven_optimal"] = False
                    entry["bound_source"] = (
                        "persisted live events; final worker export unavailable"
                    )
                else:
                    result = json.loads((folder / "result.json").read_text())
                problem = problems[case]
                if case == "R":
                    plan = read_reservoir_cp_checkpoint(folder / "best.json", problem)
                else:
                    plan = read_ddd_cp_sat_checkpoint(
                        folder / "best.json",
                        problem=problem,
                        manifest=validate_ddd_cp_sat_domain(problem),
                    )
                _, checked = validate_plan(problem, plan)
                ub = checked["journey_time_tick" if case == "R" else "unserved"]
                if (
                    "validated_upper_bound" in result
                    and ub != result["validated_upper_bound"]
                ):
                    raise ValueError(
                        "saved result differs from independently checked certificate"
                    )
                lb = max(
                    original["common_bounds"][case], result.get("lower_bound") or 0
                )
                if lb > ub:
                    raise ValueError("bound exceeds checked solution")
                events = json.loads((folder / "validated_curve.json").read_text())[
                    "events"
                ]
                best, improvements = reference, []
                for event in events:
                    value = event["validated_objective"]
                    if value < best:
                        improvements.append(event)
                        best = value
                    curve_rows.append(
                        {
                            "case": case,
                            "backend": backend,
                            "repetition": repeat,
                            "elapsed_seconds": event["elapsed_seconds"],
                            "validated_upper_bound": value,
                            "common_lower_bound": original["common_bounds"][case],
                            "bound_scope": "common certified constant; native time history stays in result.json",
                        }
                    )
                if name not in entries:
                    entry["recovered_after_supervisor_error"] = True
                    entry["supervisor_error"] = (
                        "PermissionError from macOS killpg at final deadline; solver wrote result and exited; no surviving solver process was observed."
                    )
                    entry["metrics"] = {
                        "civil_wall_seconds": None,
                        "awake_wall_seconds": None,
                        "peak_process_tree_rss_bytes": None,
                        "sampled_process_tree_cpu_seconds": None,
                        "peak_sampled_thread_count": None,
                    }
                entry.update(
                    status=result["status"],
                    validated_upper_bound=ub,
                    native_lower_bound=result.get("lower_bound"),
                    comparable_lower_bound=lb,
                    gap=(ub - lb) / ub if ub else 0,
                    strict_improvements=len(improvements),
                    first_observed_improvement_seconds=improvements[0][
                        "elapsed_seconds"
                    ]
                    if improvements
                    else None,
                    last_observed_improvement_seconds=improvements[-1][
                        "elapsed_seconds"
                    ]
                    if improvements
                    else None,
                    worker_total_seconds=result.get("runner_total_seconds"),
                    model_stats=result.get("stats"),
                )
                rows.append(entry)
                atomic_json(
                    folder / "reviewed_config.json",
                    {
                        "case": case,
                        "backend": backend,
                        "objective": original["instances"][case]["objective"],
                        "reference": reference,
                        "domain_fingerprint": original["instances"][case][
                            "domain_fingerprint"
                        ],
                        "formulation": "legacy" if backend == "cp_sat" else "native_v1",
                        "seed": repeat,
                        "requested_workers": 12,
                        "time_budget_including_build_seconds": 150,
                        "recorded_after_run_from_frozen_campaign_source": True,
                    },
                )
    for backend in ("tempest", "patty"):
        for operation in ("fixed_k", "reservoir"):
            rows.append(
                {
                    "backend": backend,
                    "operation": operation,
                    "status": "NOT_STARTED",
                    "reason": "no certified exact temporal adapter",
                }
            )
    manifest.update(
        cases=rows,
        complete=True,
        complete_scope="all eligible slots accounted for; unavailable engines remain untested",
        finalization_civil_seconds=time.time() - original["started_unix"],
        recommendations=assess_campaign(rows),
        analysis_source_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    )
    atomic_json(root / "campaign_reviewed.json", manifest)
    with (root / "progress.csv").open("w") as stream:
        writer = csv.DictWriter(
            stream,
            fieldnames=list(curve_rows[0])
            if curve_rows
            else [
                "case",
                "backend",
                "repetition",
                "elapsed_seconds",
                "validated_upper_bound",
                "common_lower_bound",
                "bound_scope",
            ],
        )
        writer.writeheader()
        writer.writerows(curve_rows)
    lines = [
        "# Native solver campaign — independently reviewed",
        "",
        "Engine admission and its scope are recorded in campaign.json. Interrupted exports remain marked INTERRUPTED; saved certificates are independently revalidated, and recovered live bounds are identified separately.",
        "",
        "| Case | Engine | Repeat | Status | Validated UB | Comparable LB | Improvements | Last observed improvement (s) |",
        "|---|---|---:|---|---:|---:|---:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {r.get('case', r.get('operation'))} | {r['backend']} | {r.get('repetition', '—')} | {r['status']} | {r.get('validated_upper_bound', '—')} | {r.get('comparable_lower_bound', '—')} | {r.get('strict_improvements', '—')} | {r.get('last_observed_improvement_seconds', '—')} |"
        )
    lines.extend(
        [
            "",
            "R uses person-microseconds; C uses persons. Reference adoption is not improvement. Checkpoint timestamps are sampled; raw solver event timestamps remain in each result.json.",
            "",
            "Missing process metrics remain unavailable. Original campaign.json and frozen sources are preserved; result.json is never synthesized for an interrupted worker.",
            "",
            f"Campaign recorded duration: {original.get('actual_civil_seconds', 'unavailable')} s. Elapsed civil time through this review: {manifest['finalization_civil_seconds']:.2f} s. A later review does not restart any solver.",
            "",
            "Recommendation thresholds and both confirmation repetitions are evaluated in campaign_reviewed.json; unavailable slots do not count as successful tests.",
        ]
    )
    (root / "report_reviewed.md").write_text("\n".join(lines) + "\n")
    print(
        json.dumps(
            {
                "finalization_seconds": manifest["finalization_civil_seconds"],
                "runs": [r for r in rows if r.get("validated_upper_bound") is not None],
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
